CREATE TABLE IF NOT EXISTS wm_pilot_access (
 org_id BIGINT UNSIGNED NOT NULL,user_id BIGINT UNSIGNED NOT NULL,
 scope ENUM('finance','hr','executive') NOT NULL,
 granted_by BIGINT UNSIGNED NOT NULL,created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 PRIMARY KEY(org_id,user_id,scope)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS wm_pilot_client_meta (
 org_id BIGINT UNSIGNED NOT NULL,lead_id BIGINT UNSIGNED NOT NULL,
 channel ENUM('unknown','direct','distributor','partner') NOT NULL DEFAULT 'unknown',
 latitude DECIMAL(9,6) NULL,longitude DECIMAL(9,6) NULL,source_note VARCHAR(1000) NOT NULL DEFAULT '',
 version INT UNSIGNED NOT NULL DEFAULT 1,updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 PRIMARY KEY(org_id,lead_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS wm_pilot_opportunity_meta (
 org_id BIGINT UNSIGNED NOT NULL,opportunity_id BIGINT UNSIGNED NOT NULL,
 probability_bps SMALLINT UNSIGNED NULL,closed_date DATE NULL,source_note VARCHAR(1000) NOT NULL DEFAULT '',
 version INT UNSIGNED NOT NULL DEFAULT 1,updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 PRIMARY KEY(org_id,opportunity_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS wm_pilot_stock (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,org_id BIGINT UNSIGNED NOT NULL,
 sku VARCHAR(80) NOT NULL,warehouse VARCHAR(100) NOT NULL,unit VARCHAR(30) NOT NULL,
 quantity DECIMAL(15,3) NOT NULL,reserved DECIMAL(15,3) NOT NULL,reorder_point DECIMAL(15,3) NOT NULL,
 counted_date DATE NOT NULL,source_note VARCHAR(1000) NOT NULL,active TINYINT UNSIGNED NOT NULL DEFAULT 1,
 version INT UNSIGNED NOT NULL DEFAULT 1,updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 UNIQUE KEY org_sku_warehouse(org_id,sku,warehouse)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS wm_pilot_receivables (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,org_id BIGINT UNSIGNED NOT NULL,lead_id BIGINT UNSIGNED NULL,
 reference VARCHAR(100) NOT NULL,currency ENUM('TND','EUR','USD') NOT NULL,
 total_amount DECIMAL(15,3) NOT NULL,paid_amount DECIMAL(15,3) NOT NULL,
 invoice_date DATE NOT NULL,due_date DATE NOT NULL,source_note VARCHAR(1000) NOT NULL,
 active TINYINT UNSIGNED NOT NULL DEFAULT 1,version INT UNSIGNED NOT NULL DEFAULT 1,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 UNIQUE KEY org_reference(org_id,reference),KEY org_due(org_id,due_date)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS wm_pilot_hr_snapshots (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,org_id BIGINT UNSIGNED NOT NULL,
 snapshot_date DATE NOT NULL,department VARCHAR(100) NOT NULL,
 staff_count INT UNSIGNED NOT NULL,absent_count INT UNSIGNED NOT NULL,
 planned_hours DECIMAL(12,2) NOT NULL,worked_hours DECIMAL(12,2) NOT NULL,overtime_hours DECIMAL(12,2) NOT NULL,
 source_note VARCHAR(1000) NOT NULL,version INT UNSIGNED NOT NULL DEFAULT 1,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 UNIQUE KEY org_date_department(org_id,snapshot_date,department)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS wm_pilot_actions (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,org_id BIGINT UNSIGNED NOT NULL,
 alert_key CHAR(64) NOT NULL,scope VARCHAR(20) NOT NULL,entity_type VARCHAR(30) NOT NULL,entity_id BIGINT UNSIGNED NOT NULL,
 title VARCHAR(250) NOT NULL,next_action VARCHAR(1000) NOT NULL,
 owner_id BIGINT UNSIGNED NULL,due_date DATE NULL,status ENUM('open','done','dismissed') NOT NULL DEFAULT 'open',
 created_by BIGINT UNSIGNED NOT NULL,version INT UNSIGNED NOT NULL DEFAULT 1,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 UNIQUE KEY org_alert(org_id,alert_key),KEY org_scope(org_id,scope,status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
