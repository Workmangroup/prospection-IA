-- Ajout de tables ; aucune modification des données ou tables existantes.
CREATE TABLE IF NOT EXISTS wm_crm_contacts (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 org_id BIGINT UNSIGNED NOT NULL, lead_id BIGINT UNSIGNED NOT NULL,
 full_name VARCHAR(200) NOT NULL, role_text VARCHAR(200) NOT NULL DEFAULT '',
 email VARCHAR(254) NOT NULL DEFAULT '', phone VARCHAR(60) NOT NULL DEFAULT '',
 notes TEXT NOT NULL, active TINYINT UNSIGNED NOT NULL DEFAULT 1,
 version INT UNSIGNED NOT NULL DEFAULT 1,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 KEY org_lead(org_id,lead_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS wm_workwear_profiles (
 org_id BIGINT UNSIGNED NOT NULL, lead_id BIGINT UNSIGNED NOT NULL,
 wearer_count INT UNSIGNED NULL,
 garments TEXT NOT NULL, ppe TEXT NOT NULL, standards TEXT NOT NULL,
 sizing TEXT NOT NULL, branding TEXT NOT NULL, renewal TEXT NOT NULL,
 supplier TEXT NOT NULL, constraints_text TEXT NOT NULL,
 version INT UNSIGNED NOT NULL DEFAULT 1,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 PRIMARY KEY(org_id,lead_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
